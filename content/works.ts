/**
 * 施工実績のデータ。一覧(/works)・詳細(/works/[slug])・TOPの実績セクションが
 * 共有する唯一の情報源。
 *
 * このファイルは content/ 配下（サイトに載せる「中身」を置く層）にある。
 * 技術ユーティリティは lib/ に分けてある。
 *
 * 写真は scripts/build-works-images.mjs が public/works/<slug>/ に書き出したもの。
 * ファイル名だけを持ち、パスの組み立ては workImage() に寄せている。
 */
export type WorkCategory = "store" | "facility";

/** 1枚の写真と、それが施工前か施工後か。 */
export type Shot = { file: string; state: "before" | "after" };

export type Work = {
  slug: string;
  title: string;
  category: WorkCategory;
  /** "飲食店 / 新装" のような業種と工事種別 */
  type: string;
  summary: string;
  /** 一覧のカバー画像(ファイル名) */
  cover: string;
  /**
   * 施工年月("YYYY-MM")。グループのアイム建築事業部サイト(aim-architecture.net)の
   * 掲載情報を参照している。同サイトに掲載がない案件は未設定(undefined)にし、
   * 一覧・詳細では年月を表示しない(不確かな年月を表示しない)。
   * 並び順(WORKS配列の並び)もこの年月の新しい順にしてある。
   */
  date?: string;
  /**
   * 施工の記録。同じ場所の前後が隣り合うよう並べ替えてある。
   * 詳細ページはこの1本だけを見せる。案件によって写真の揃い方が違っても
   * ページの構成が変わらないようにするため、施工前と施工後で列を分けない。
   */
  shots: Shot[];
  /**
   * トップ写真の前後比較(パイロット)。同じアングル・同じ画角で撮れた1組が
   * ある案件だけ設定する。「施工の記録」冒頭で、スクロール連動のワイプ演出
   * として見せる(WorkCompareHero)。未設定の案件は何も表示しない。
   */
  heroCompare?: { before: string; after: string };
};

export const CATEGORY_LABEL: Record<WorkCategory, string> = {
  store: "店舗・住宅施工",
  facility: "施設営繕・解体",
};

export const STATE_LABEL: Record<Shot["state"], string> = {
  before: "施工前",
  after: "施工後",
};

/** "YYYY-MM" を "2026年5月" のような表示用の文字列に整える。 */
export function formatWorkDate(date: string): string {
  const [y, m] = date.split("-");
  return `${y}年${Number(m)}月`;
}

